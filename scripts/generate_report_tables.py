"""Generate the LaTeX tables of the technical report from the measured metrics.

The report must never display a number that was not computed. This script
reads ``artifacts/metrics.json`` (produced by ``src/models/evaluate.py``) and
writes ``reports/metrics_table.tex``. When the file does not exist - the
evaluation has not been run yet - the generated table explicitly says so.

Usage::

    python scripts/generate_report_tables.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.config import BENCHMARK_JSON, METRICS_JSON  # noqa: E402

DEFAULT_OUTPUT = REPO_ROOT / "reports" / "metrics_table.tex"

NOT_MEASURED = r"\textcolor{warn}{\textbf{non mesuré}}"


def _format(value: Optional[float], digits: int = 3) -> str:
    if value is None:
        return NOT_MEASURED
    return f"{value:.{digits}f}"


def _escape(name: str) -> str:
    """Escape the LaTeX special characters of a class name."""
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
    }
    for char, replacement in replacements.items():
        name = name.replace(char, replacement)
    return name


def build_table(metrics: Optional[Dict], benchmark: Optional[Dict]) -> str:
    """Return the LaTeX source of the measured-metrics table."""
    lines: List[str] = []
    lines.append("% Auto-generated by scripts/generate_report_tables.py - do not edit.")
    lines.append("% The values below are read from artifacts/metrics.json.")
    lines.append(r"\begin{tabular}{@{}lr@{}}")
    lines.append(r"\toprule")
    lines.append(r"\textbf{Métrique mesurée} & \textbf{Valeur} \\")
    lines.append(r"\midrule")

    if not metrics:
        lines.append(rf"Statut & {NOT_MEASURED} \\")
        lines.append(r"\bottomrule")
        lines.append(r"\end{tabular}")
        return "\n".join(lines) + "\n"

    lines.append(rf"mAP@0.5 (test) & {_format(metrics.get('test_mAP50'))} \\")
    lines.append(rf"mAP@0.5:0.95 (test) & {_format(metrics.get('test_mAP50_95'))} \\")
    lines.append(rf"Precision (test) & {_format(metrics.get('precision'))} \\")
    lines.append(rf"Recall (test) & {_format(metrics.get('recall'))} \\")

    per_class = metrics.get("per_class_ap50_95") or {}
    if per_class:
        lines.append(r"\midrule")
        lines.append(r"\textbf{AP50-95 par classe (test)} & \\")
        for name, value in per_class.items():
            lines.append(rf"  \quad {_escape(str(name))} & {_format(value)} \\")

    if benchmark:
        lines.append(r"\midrule")
        lines.append(r"\textbf{Latence (mesurée)} & \\")
        pytorch_ms = benchmark.get("pytorch_median_ms")
        onnx_ms = benchmark.get("onnx_median_ms")
        speedup = benchmark.get("speedup_x")
        if pytorch_ms is not None:
            value = _format(pytorch_ms, 1)
            lines.append(rf"  \quad PyTorch (médiane) & {value}\,\mathrm{{ms}} \\")
        if onnx_ms is not None:
            value = _format(onnx_ms, 1)
            lines.append(rf"  \quad ONNX Runtime (médiane) & {value}\,\mathrm{{ms}} \\")
        if speedup is not None:
            value = _format(speedup, 2)
            lines.append(rf"  \quad Accélération & {value}\times \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the report tables")
    parser.add_argument("--metrics", default=str(METRICS_JSON))
    parser.add_argument("--benchmark", default=str(BENCHMARK_JSON))
    parser.add_argument("--out", default=str(DEFAULT_OUTPUT))
    args = parser.parse_args()

    metrics = None
    benchmark = None

    metrics_path = Path(args.metrics)
    if metrics_path.exists():
        try:
            metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            print(f"⚠️  {metrics_path} is not valid JSON ({exc}) - ignored.")

    benchmark_path = Path(args.benchmark)
    if benchmark_path.exists():
        try:
            benchmark = json.loads(benchmark_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            benchmark = None

    output = Path(args.out)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build_table(metrics, benchmark), encoding="utf-8")

    if metrics:
        print(f"✅ Measured metrics written to {output}")
    else:
        print(f"⚠️  No metrics.json found - {output} states that the evaluation "
              f"has not been run yet.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
